# Generate native/gpu/seed/r1_enum.cpp = src/seed_enum.cpp with cost-bucketed enumeration (R1 probe,
# reports/r1-probe-1110/). Bank level k now holds programs of integer cost k, where
# cost(op(c1..cn)) = w(op) + sum cost(ci), leaves cost 1, lambda bodies keep cost = size.
# w(op) is read from the file named by ARC_R1_COSTS ("prim cost" lines, cost >= 1); unset or all-1 -> the
# original size order exactly. Nothing is dropped: every (op, split) of every bucket is still enumerated.
