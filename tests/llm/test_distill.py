import json

from arcagi.llm import distill as ds


def test_fragments_skip_bare_and_learned_steps():
    prog = [["crop_bbox"], ["resize_crop", ["const", 3], ["const", 3]], ["flip_lr"]]
    frags = list(ds.fragments(prog))
    assert [["crop_bbox"]] not in frags and [["flip_lr"]] not in frags
    assert [prog[1]] in frags and prog in frags and prog[:2] in frags
    learned = [["crop_bbox"], ["colormap", [[1, 2]]]]
    assert list(ds.fragments(learned)) == []


def test_synth_rate_identity_fails_on_real_task():
    rate = ds.synth_rate("0520fde7", [["split_overlay", "v", "and"]])
    if rate is not None:  # data_synth is regenerated by a script, may be absent
        assert rate == 0.0  # MARK left unresolved never equals the output
    good = [["split_overlay", "v", "and"], ["colormap", [[10, 2]]]]
    rate = ds.synth_rate("0520fde7", good)
    assert rate is None or rate > 0  # re-arc recolors, so a fixed 2 can miss


def _report(path, rows):
    tasks = []
    for tid, correct, prog in rows:
        att = [{"selected": True, "program": json.dumps(prog)}] if prog else []
        tasks.append({"task_id": tid, "correct": correct, "trace": {"attempts": att}})
    path.write_text(json.dumps({"tasks": tasks}))


def test_reuse_verdicts(tmp_path, monkeypatch):
    staged = {
        "m_llm_a": {"kind": "transform", "body": [["flip_lr"]], "origin": ["t1"]},
        "m_llm_b": {"kind": "transform", "body": [["flip_ud"]], "origin": ["t1"]},
        "m_llm_c": {"kind": "transform", "body": [["rot90"]], "origin": ["t1"]},
    }
    (tmp_path / "staged.json").write_text(json.dumps(staged))
    _report(tmp_path / "base.json", [("t1", False, None), ("t2", True, [["x"]])])
    _report(
        tmp_path / "llm.json",
        [
            ("t1", True, [["m_llm_b"]]),
            ("t2", True, [["m_llm_a"]]),
            ("t3", True, [["m_llm_c"]]),
        ],
    )
    rates = {"t1": 1.0, "t2": 0.9, "t3": 0.1}
    monkeypatch.setattr(ds, "synth_rate", lambda task, prog: rates[task])
    res = ds.reuse(tmp_path, tmp_path / "base.json", tmp_path / "llm.json")
    verdicts = {k: v["verdict"] for k, v in res["pieces"].items()}
    assert verdicts == {
        "m_llm_a": "reused",
        "m_llm_b": "origin_only",
        "m_llm_c": "memorized",
    }
    assert res["gained"] == ["t1", "t3"] and res["regressed"] == []
